"""Write the list of every widget method Forever documents, for the regression stubs.

Usage: python3 Tools/build/gen_widget_methods.py --source <wow-ui-source on branch forever>
                                                 [--out Tools/regression/stubs/widget_methods.lua]

A widget method is a function in a generated documentation table whose Type is "ScriptObject"
(SimpleFrameAPI, SimpleTextureAPI, SimpleStatusBarAPI and the rest). The stubs answer only these
names, so a test fails when addon code calls a method Forever does not have.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

DOCS = Path("Interface") / "AddOns" / "Blizzard_APIDocumentationGenerated"
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "regression" / "stubs" / "widget_methods.lua"
SCRIPT_OBJECT = re.compile(r'^\tType = "ScriptObject",$', re.M)
FUNCTION = re.compile(r'^\t\t\tName = "(\w+)",\n\t\t\tType = "Function",$', re.M)


def collect(source):
    """Return the sorted, de-duplicated widget method names documented under source."""
    names = set()
    for path in sorted((Path(source) / DOCS).glob("*.lua")):
        text = path.read_text(encoding="utf-8", errors="replace")
        if SCRIPT_OBJECT.search(text):
            names.update(FUNCTION.findall(text))
    return sorted(names)


def describe(source):
    """Return "<short hash> <subject>" for the source checkout's HEAD commit."""
    result = subprocess.run(
        ["git", "-C", str(source), "log", "-1", "--format=%h %s"], capture_output=True, text=True
    )
    if result.returncode != 0:
        raise RuntimeError(f"{source} is not a git checkout: {result.stderr.strip()}")
    return result.stdout.strip()


def render(names, commit):
    lines = [
        f"-- widget_methods.lua: every widget method Forever documents, from wow-ui-source {commit}."
        " Generated by Tools/build/gen_widget_methods.py; do not edit.",
        "return {",
    ]
    lines += [f'\t"{name}",' for name in names]
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_atomically(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(tmp, path)
    except BaseException:
        os.unlink(tmp)
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True, type=Path, help="wow-ui-source checkout on branch forever")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Lua file to write")
    args = parser.parse_args(argv)

    if not (args.source / DOCS).is_dir():
        print(f"error: {args.source / DOCS} does not exist", file=sys.stderr)
        return 1
    names = collect(args.source)
    if not names:
        print(f"error: no widget methods found in {args.source / DOCS}", file=sys.stderr)
        return 1
    try:
        commit = describe(args.source)
    except RuntimeError as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    write_atomically(args.out, render(names, commit))
    print(f"wrote {len(names)} widget methods to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
