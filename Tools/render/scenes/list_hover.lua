-- list_hover.lua: hovered widget and Options category rows for pixel comparisons of the shared wash.
local Common = dofile("Tools/render/scenes/_common.lua")
local O = dofile("Tools/regression/options_env.lua")

return Common.Run(function()
	local env, K, ns = O.New(Common.ScreenOpts({ setup = Common.ForceScreen }))
	local panel = K.Widgets.Panel(K.Scale.Root(), { width = 600, height = 180 })
	panel:SetPoint("CENTER", K.Scale.Root(), "CENTER")
	local list = K.Widgets.ScrollList(panel, { width = 250, height = 120, stagger = false })
	list:SetPoint("TOPLEFT", panel, "TOPLEFT", 20, -20)
	list:SetData({ "A hovered row", "Another row" })
	local rail = ns.Rail.Create(panel)
	rail:SetSize(250, 120)
	rail:SetPoint("TOPRIGHT", panel, "TOPRIGHT", -20, -20)
	rail:SetPages({ { id = "one", label = "A hovered category" }, { id = "two", label = "Another category" } })
	O.W.Enter(list.rows[1])
	O.W.Enter(rail.rows[1])
	O.W.Settle(env)
	assert(not Common.Errors(env, K), Common.Errors(env, K))
	local Boot = dofile("Tools/regression/questcard_guide_env.lua")
	local R = Boot(Common.SCREEN)
	R.K.Options.Write("HudStyle", "style", (os.getenv("RENDER_HUD_STYLE") or "Frames"):lower())
	R.settle()
	R.rxp.activeItemFrame.buttonList[1].icon:SetTexture(132794)
	R.rxp.targeting.activeTargetFrame.enemyTargetButtons[1].icon:SetTexture(136188)
	O.W.Enter(R.ns.Quests.Rows()[1])
	return Common.Scene.Merge({ Common.Scene.Build(env), Common.Scene.Build(R.env, { iconDirs = Common.IconDirs() }) })
end)
