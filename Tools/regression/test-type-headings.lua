-- test-type-headings.lua: tabs, section caps, card figures and option help share one hierarchy with an original-look switch.
local O = dofile("Tools/regression/options_env.lua")
local env, K, ns = O.New()
local W, T = K.Widgets, K.Tokens
local holder = env.CreateFrame("Frame", nil, K.Scale.Root())
holder:SetSize(700, 400)
local tabs = W.Tabs(holder, { tabs = { { value = "one", label = "One tab" } } })
assert(tabs.buttons[1].label:GetFont() == T.Font("caps"), "C5: tabs use the section caps face")
local cap = W.SectionCap(holder, { text = "A section", count = 7 })
assert(cap.count:GetFont() == T.Font("number"), "card-header figures follow the number role")
local gold = { T.Color("capsGold") }
local r, g, b = cap.label:GetTextColor()
assert(r == gold[1] and g == gold[2] and b == gold[3], "C5: section headings keep the gold token")
local rr, rg, rb = unpack(cap.rule._state.ColorTexture)
assert(rr == gold[1] and rg == gold[2] and rb == gold[3], "C5: the section rule uses gold even on Medallions steel")
local list = { view = holder, GetViewWidth = function() return 700 end }
local row = ns.Rows.Create(list)
ns.Rows.Update(row, { kind = "toggle", label = "A label", help = "A help line", get = function() return true end }, nil, list)
local _, labelSize = row.label:GetFont()
local _, helpSize = row.help:GetFont()
assert(labelSize == W.FontSize(row.label, 12) and helpSize == W.FontSize(row.help, 11), "C5: option label 12 and help 11, each floored")
K.Options.Write("Appearance", "sectionHeadings", false)
assert(tabs.buttons[1].label:GetFont() == T.Font("body"), "C5 off: restore body-face tabs")
assert(cap.count:GetFont() == T.Font("number"), "C3 off: restore card-header number role")
local _, oldLabel = row.label:GetFont()
local _, oldHelp = row.help:GetFont()
assert(oldLabel == oldHelp, "C5 off: restore equal-size label and help")
K.Options.Write("Appearance", "sectionHeadings", true)
holder:SetScale(0.65)
tabs:Restyle()
assert(tabs.buttons[1].label:GetFont() == T.Font("caps"), "C5: scaled tabs keep their caps face")
K.Theme.SetRoleFonts({ caps = "AlegreyaSansRegular" })
assert(tabs.buttons[1].label:GetText():find("\226\128\137", 1, true), "C5: thin spaces are allowed when Locale.TrackMode says space")
K.Theme.SetRoleFonts({})
assert(not tabs.buttons[1].label:GetText():find("\226\128\137", 1, true), "C5: baked caps never gain thin spaces")
assert(#env._errors == 0, tostring(env._errors[1]))
print("test-type-headings: caps, card figures, option hierarchy and original-look switch")
local S = dofile("Tools/regression/skins_env.lua")
local skinEnv, skinK, skin = S.New()
skinK.Modules.Enable("Skins")
local card = skin.Lumen.SectionCap(skinK.Scale.Root())
card:SetSize(300, 24)
card:SetText("Quests")
card:SetCount("Step 134")
assert(card.count:GetFont() == skinK.Tokens.Font("number"), "story-card figures follow the number role")
local _, capSize = card.label:GetFont()
assert(capSize == skinK.Widgets.FontSize(card.label, 10 * skinK.Theme.FontScale()), "C5: story-card headings share the ten-unit caps size and floor")
local _, relative = card.rule:GetPoint(1)
assert(relative == card, "C5: the story rule spans below the heading")
skinK.Options.Write("Appearance", "sectionHeadings", false)
assert(card.count:GetFont() == skinK.Tokens.Font("number"), "C3 off: story-card figures restore the number role")
assert(select(2, card.label:GetFont()) == skinK.Widgets.FontSize(card.label, 12 * skinK.Theme.FontScale()), "C5 off: restore the original story heading size")
assert(#skinEnv._errors == 0, tostring(skinEnv._errors[1]))

for _, headings in ipairs({ true, false }) do
	skinK.Options.Write("Appearance", "sectionHeadings", headings)
	skinK.Theme.SetRoleFonts({ number = "SourceSans3Semibold" })
	assert(card.count:GetFont() == skinK.Tokens.Font("number"), "cap asides must respect an explicit number-role font in every HUD and heading mode")
end
