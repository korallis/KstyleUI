-- test-skins-button-material.lua: skinned controls have a material fill, a visible edge, a lit top edge and a distinct pressed state.
local S = dofile("Tools/regression/skins_env.lua")
local env, K, ns = S.New({ setup = function(e)
	e.CreateColor = function(r, g, b, a) return { r = r, g = g, b = b, a = a } end
end })
K.Modules.Enable("Skins")
local B = S.Blizzard(env)
local button = B.frame("Button", K.Scale.Root())
button:SetSize(100, 28)
button:SetFontString(B.text(button))
K.Skin.Button(button)
ns.PartBKit.Accent(button)
local parts = K.Skin.Parts(button)
assert(parts.material and parts.topLine, "give skinned buttons a vertical material fill and a one-pixel top line")
assert(S.W.SameRGB(parts.backdrop.chrome.rim[1], K.Tokens.Color("medGunLit")), "use medGunLit for an enabled button's edge")
local gradient = S.W.LastCall(parts.material, "SetGradient")
assert(gradient and gradient[1] == "VERTICAL", "skin button material runs vertically")
S.W.Down(button)
local fill = S.W.LastCall(parts.material, "SetColorTexture")
assert(fill and fill[1] == K.Tokens.Color("slotFill"), "pressed buttons use slotFill")
S.W.Up(button)
button:Disable()
assert(S.W.SameRGB(parts.backdrop.chrome.rim[1], K.Tokens.Color("medRimLit")), "disabled buttons have the muted material edge")
local r, g, b = button:GetFontString():GetTextColor()
local er, eg, eb = K.Tokens.Color("textDisabled")
assert(r == er and g == eg and b == eb, "disabled buttons use textDisabled")
assert(#env._errors == 0 and K.ErrorCount() == 0, tostring(env._errors[1]))
print("skins button material ok")
