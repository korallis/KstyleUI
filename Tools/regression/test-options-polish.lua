-- test-options-polish.lua: body text keeps its floor at a 0.65 window scale; preview, switch and column choices restore their previous presentation.
local O = dofile("Tools/regression/options_env.lua")
local W = O.W
local env, K, ns = O.New()
local function settle()
	env.RunTimers()
	W.Settle(env)
	env.RunTimers()
end
K.Options.Open("General")
settle()
K.Layout.Set("Options.Window", "scale", 0.65)
settle()
local function floorText(text)
	local _, size = text:GetFont()
	local pixels = size * K.Widgets.ScaleFactor(text:GetParent()) / K.Scale.Pixel(1)
	assert(pixels >= K.Scale.TextFloor() - 0.01,
		"G4: reapply body fonts after the window scale changes; " .. tostring(text:GetText()) .. " draws at " .. pixels .. " px")
end
local parts = ns.Window.Parts()
for _, row in ipairs(parts.content.rows) do
	if row:IsShown() and row.item and row.item.kind ~= "header" then floorText(row.label); floorText(row.help) end
end
for _, row in ipairs(parts.rail.rows) do if row:IsShown() then floorText(row.label) end end
floorText(parts.search)
floorText(parts.layoutButton.label)
K.Options.Write("OptionsPresentation", "readableText", false)
settle()
local _, oldSize = parts.search:GetFont()
assert(oldSize * K.Widgets.ScaleFactor(parts.search) / K.Scale.Pixel(1) < K.Scale.TextFloor(), "G4: turning Off restores previous text scaling immediately")
K.Options.Write("OptionsPresentation", "readableText", true)
settle()
floorText(parts.search)
local Scene = dofile("Tools/render/scene.lua")
local win = ns.Window.Frame()
local _, railTop = Scene.Rect(env, win.categoryCap)
local _, pageTop = Scene.Rect(env, win.pageCap)
local _, previewTop = Scene.Rect(env, parts.preview.caption)
assert(math.abs(railTop - pageTop) < 1 and math.abs(pageTop - previewTop) < 1, "G4: the three column headings share one top line")
K.Options.Write("OptionsPresentation", "columns", false)
settle()
assert(not win.categoryCap:IsShown() and not win.pageCap:IsShown(), "G4: Off restores the previous columns")
local toggle = K.Widgets.Toggle(K.Scale.Root(), { value = true })
assert(toggle.trackBox:GetHeight() == 20 and W.SameColor(toggle.fill[2], K.Widgets.MixTokens("surface", 1, "accent", 1, 0.65)), "G4: slim switches have the brighter On fill")
K.Options.Write("OptionsPresentation", "switches", false)
settle()
assert(toggle.trackBox:GetHeight() == 28 and W.SameColor(toggle.fill[2], K.Widgets.MixTokens("surface", 1, "accent", 1, 0.3)), "G4: Off restores the previous switch geometry and fill")
local oldEnv, oldK, old = O.New({ before = function(_, core) core.Options.Write("OptionsPresentation", "readableText", false) end })
oldK.Options.Open("General")
W.Settle(oldEnv)
oldK.Layout.Set("Options.Window", "scale", 0.65)
W.Settle(oldEnv)
local _, size = old.Window.Parts().search:GetFont()
assert(size * oldK.Widgets.ScaleFactor(old.Window.Parts().search) / oldK.Scale.Pixel(1) < oldK.Scale.TextFloor(), "G4: Off restores previous window text scaling")
local savedEnv, savedK, saved = O.New({ before = function(_, core) core.Store.Layout()["Options.Window"] = { scale = 0.65 } end })
savedK.Options.Open("General")
W.Settle(savedEnv)
local savedSearch = saved.Window.Parts().search
local _, savedSize = savedSearch:GetFont()
assert(savedSize * savedK.Widgets.ScaleFactor(savedSearch) / savedK.Scale.Pixel(1) >= savedK.Scale.TextFloor() - 0.01, "G4: first opening at a saved 0.65 scale also keeps the floor")
assert(#env._errors == 0, table.concat(env._errors, "\n"))
print("options polish ok")
