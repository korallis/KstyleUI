local U = dofile("Tools/regression/unitframes_env.lua")
local env, K, ns = U.New()
K.Options.Write("Appearance", "readableBars", false)
K.Options.Write("Appearance", "worldText", false)
local cb = ns.CastBars.Get("player")[1]
assert(cb.text:GetFont() == K.Tokens.Font("caps"), "off restores the original cast caption face")
assert(select(3, cb.timer:GetFont()) == "", "off restores the original cast timer without an outline")
assert(select(3, ns.Settings.Font("player", "health")) == "", "world text off restores the soft-shadow unit default")
K.Options.Write("Appearance", "worldText", true)
K.Options.Write("UnitFrames", "player.fonts.health.outline", "NONE")
assert(select(3, ns.Settings.Font("player", "health")) == "", "an explicit soft-shadow choice overrides inherited readability")
K.Options.Write("Appearance", "worldText", false)
local view = ns.Frames.Get("player").views[1]
assert(not view.name.inkScrim or not view.name.inkScrim[5]:IsShown(), "world text off hides header backing")
assert(#env._errors == 0, tostring(env._errors[1]))

local C = dofile("Tools/regression/chat_env.lua")
local ce, CK, cn = C.New()
C.Enable(ce, CK)
ce.RunTimers()
ce.ChatFrame1Tab:SetAlpha(0.2)
CK.Options.Write("Appearance", "barColors", false)
CK.Options.Write("Appearance", "chatTabs", false)
assert(ce.ChatFrame1Tab:GetAlpha() == 0.2, "off restores the client's requested tab alpha")
local geometry = cn.Panel.Geometry(ce.ChatFrame1)
assert(geometry.top == geometry.divider, "off restores the original message inset")
local underline = CK.Skin.Parts(ce.ChatFrame1Tab).underline
assert(select(2, underline:GetPoint(1)) == ce.ChatFrame1Tab, "off restores the tab-width underline")
assert(#ce._errors == 0, tostring(ce._errors[1]))

local S = dofile("Tools/regression/skins_env.lua")
local se, SK, sn = S.New()
SK.Modules.Enable("Skins")
local bar = se.CreateFrame("StatusBar", nil, SK.Scale.Root())
bar:SetSize(240, 20)
bar.rankText = SK.Widgets.FontString(bar, "OVERLAY")
local kit = sn.PartBKit.Bar(bar, { label = "Skill" })
assert(bar:GetHeight() == SK.Widgets.Snap(bar, 6) and kit.rankOutside, "readable skin bars use the outside caption layout")
SK.Options.Write("Appearance", "readableBars", false)
assert(bar:GetHeight() == 20 and not kit.rankOutside, "off restores the original bar height and reachable inside rank path")
assert(select(1, kit.label:GetPoint()) == "LEFT", "off restores the in-bar label anchor")
SK.Options.Write("Appearance", "readableBars", true)
assert(bar:GetHeight() == SK.Widgets.Snap(bar, 6) and kit.rankOutside, "the same existing bar switches back on")
assert(#se._errors == 0, tostring(se._errors[1]))
print("readability off restores module faces, geometry and alpha")
