local W = dofile("Tools/regression/widget_env.lua")
local env, K = W.New()
local frame = env.CreateFrame("Frame")
local texture = frame:CreateTexture(nil, "BACKGROUND")
K.Skin.Strip(frame)
texture:SetVertexColor(1, 1, 1, 1)
assert(texture:GetAlpha() == 0, "a native vertex recolor must not revive stripped backdrop art")
texture:SetVertexColor(0.5, 0.5, 0.5)
assert(texture:GetAlpha() == 0, "omitted vertex alpha must not revive stripped backdrop art")
print("stripped texture vertex alpha passed")
