-- test-type-one-voice.lua: One typeface voice and Soft glow behind world text are on by default: Medallions plate names and cast names share the effective number face (an explicit plate font still wins for the cast), a plate name sits on a one-region halo that follows the name's setting, alpha and the switch and costs nothing while off, module-outlined text casts the kit's drop shadow while a kit control outlined by Text outline keeps the outline alone, and switching each Appearance setting off restores Inter, the caps face, no halo and no shadow.
local N = dofile("Tools/regression/nameplates_env.lua")
local A = dofile("Tools/regression/auras_env.lua")

local env, K, ns = N.New()
local function set(module, key, value)
	K.Options.Write(module, key, value)
	env.RunTimers()
end

N.Add(env, "nameplate1", { name = "Decrepit Darkhound", level = 12, reaction = 2, canAttack = true })
env.RunTimers()
local plate = ns.Plates.Get("nameplate1")
local number = (K.Tokens.Font("number"))
assert(K.Appearance.Get("oneVoice") == true and K.Appearance.Get("softBacking") == true, "both settings are on by default")
assert(number == K.Tokens.FontPath("BarlowSemiBold"), "under Medallions the number face is Barlow")
assert(plate.name:GetFont() == number, "the plate name shares the number face")
assert(plate.castName:GetFont() == number, "the plate's cast name shares it too")
local sx, sy = plate.name:GetShadowOffset()
assert(sx > 0 and sy < 0 and select(3, plate.name:GetFont()) == "OUTLINE", "the outlined name casts the kit's drop shadow")

set("Appearance", "outline", "OUTLINE")
local button = K.Widgets.Button(env.UIParent, { text = "Options" })
local bx, by = button.label:GetShadowOffset()
assert(select(3, button.label:GetFont()) == "OUTLINE" and bx == 0 and by == 0, "a kit control outlined by Text outline keeps the outline alone")
sx, sy = plate.name:GetShadowOffset()
assert(sx > 0 and sy < 0, "the plate name keeps its drop shadow under Text outline")
set("Appearance", "outline", "")

local halo = plate.name.halo
assert(halo and halo:IsShown(), "the name sits on a shown halo")
assert(halo:GetParent() == plate and halo:GetDrawLayer() == "BACKGROUND", "the halo is drawn under the plate's art")
plate:SetNameAlpha(0)
assert(not halo:IsShown(), "a name faded out while casting takes its halo with it")
plate:SetNameAlpha(1)
assert(halo:IsShown(), "and brings it back")
set("Nameplates", "name.show", false)
assert(not halo:IsShown(), "hidden names leave no halo")
set("Nameplates", "name.show", true)
assert(halo:IsShown(), "shown names get it back")

set("Appearance", "softBacking", false)
assert(not halo:IsShown(), "off hides the halo")
sx, sy = plate.name:GetShadowOffset()
assert(sx == 0 and sy == 0, "off: the outline alone, as before")
set("Appearance", "oneVoice", false)
assert(plate.name:GetFont() == K.Tokens.FontPath("InterSemiBold"), "off: the plate name is Inter SemiBold again")
assert(plate.castName:GetFont() == (K.Tokens.Font("caps")), "off: the cast name is the caps face again")

N.Add(env, "nameplate2", { name = "Rotting Dead", level = 6, reaction = 2, canAttack = true })
env.RunTimers()
local plain = ns.Plates.Get("nameplate2")
assert(plain.name.halo == nil, "no halo is made while the setting is off")
assert(#A.Descendants(plate) - #A.Descendants(plain) <= 1, "the halo costs one region a plate")
local function fadeCalls(p)
	local before = A.CallCount(p)
	p:SetNameAlpha(0)
	p:SetNameAlpha(1)
	return A.CallCount(p) - before
end
assert(fadeCalls(plate) == fadeCalls(plain), "a switched-off halo costs nothing when a cast fades the name")

set("Appearance", "softBacking", true)
set("Appearance", "oneVoice", true)
assert(halo:IsShown() and plate.name:GetFont() == number, "switching both back on restores the halo and the number face")
assert(plain.name.halo, "a plate built while it was off gets its halo")

set("Appearance", "roleFontNumber", "InterSemiBold")
number = (K.Tokens.Font("number"))
assert(number == K.Tokens.FontPath("InterSemiBold"), "the number role takes the chosen face")
assert(plate.name:GetFont() == number and plate.castName:GetFont() == number, "a chosen number face reaches the plate name and cast name")
local body = (K.Tokens.Font("body"))
set("Nameplates", "font", body)
assert(plate.castName:GetFont() == body, "an explicit plate font, even the body face, keeps the cast name")

assert(#env._errors == 0, tostring(env._errors[1]))
assert(K.ErrorCount() == 0, "no errors caught by KstyleUI.Call")
print("ok - test-type-one-voice")
