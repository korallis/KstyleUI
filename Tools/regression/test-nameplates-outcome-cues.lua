-- test-nameplates-outcome-cues.lua: readable target ticks, a threat keyline and continuous plate opacity, with the old look available.
local N = dofile("Tools/regression/nameplates_env.lua")
local W = dofile("Tools/regression/widget_env.lua")
local env, K, ns = N.New()
K.Options.Write("HudStyle", "style", "medallions")
K.Options.Write("Nameplates", "threat.groupOnly", false)
N.Add(env, "nameplate1", { threat = 3 })
N.Add(env, "nameplate2", { threat = 0 })
N.Target(env, "nameplate1")
local plate, other = ns.Plates.Get("nameplate1"), ns.Plates.Get("nameplate2")
local r, g, b = K.Tokens.Color("medText")
for _, side in ipairs(plate.brackets.sides) do
	local color = N.Last(side.stroke, "SetVertexColor")
	assert(color[1] == r and color[2] == g and color[3] == b, "E4: target ticks use medText")
	assert(side.keyline and side.keyline:IsShown(), "E4: ticks have a one-pixel black keyline")
	assert(math.abs(side.open._state.Offset[1]) == K.Widgets.Snap(plate, 3), "E4: ticks travel three units")
	assert(side.reveal._state.Duration[1] == 0.12, "E4: ticks fade in over 120 ms")
end
local function rim(token)
	local er, eg, eb = K.Tokens.Color(token)
	local c = N.Last(plate.health.under.edgeHard, "SetColorTexture")
	assert(c[1] == er and c[2] == eg and c[3] == eb, "E4: threat recolours the keyline to " .. token)
	assert(not plate.threatGlow[5]:IsShown(), "E4: threat uses no additive glow")
end
rim("hostile")
env._units.nameplate1.threat = 1
plate:UpdateThreat()
rim("neutral")
K.Options.Write("Nameplates", "threat.role", "tank")
env._units.nameplate1.threat = 3
plate:UpdateThreat()
rim("friendly")
local mode = K.Options.Read("ColorVision", "mode")
K.Options.Write("ColorVision", "mode", "redGreen")
local pr, pg, pb = K.Tokens.Color("visionRGCalm")
local edge = N.Last(plate.health.under.edgeHard, "SetColorTexture")
assert(edge[1] == pr and edge[2] == pg and edge[3] == pb, "E4: threat edges preserve the selected colour-vision palette")
K.Options.Write("ColorVision", "mode", mode)
N.Focus(env, "nameplate2")
env._units.nameplate2.threat = 1
other:UpdateThreat()
local focus = ns.Settings.Get("focus.color")
edge = N.Last(other.health.under.edgeHard, "SetColorTexture")
assert(edge[1] == focus.r and edge[2] == focus.g and edge[3] == focus.b, "E4: a threat refresh preserves the focus marker")
N.Focus(env, nil)
K.Options.Write("Nameplates", "target.dimOthers", 0.4)
W.Tick(env, 0.2)
assert(other:GetAlpha() == 0.4, "E4: other plates settle at the chosen opacity")
N.Target(env, "nameplate2")
assert(other:GetAlpha() == 0.4, "E4: a target swap starts from the current alpha")
W.Tick(env, 0.1)
assert(other:GetAlpha() > 0.4 and other:GetAlpha() < 1, "E4: plate opacity tweens over 200 ms")
N.Target(env, "nameplate1")
W.Tick(env, 0.2)
assert(other:GetAlpha() == 0.4, "E4: rapid swaps replace the old opacity tween")
local recycled = N.Remove(env, "nameplate2")
assert(other:GetAlpha() == 1, "E4: a recycled plate resets its alpha before another unit uses it")
N.Add(env, "nameplate2", nil, { base = recycled })
assert(ns.Plates.Get("nameplate2") == other, "E4: the new unit reuses the cleared plate")
K.Options.Write("Nameplates", "target.readableTicks", false)
K.Options.Write("Nameplates", "threat.keyline", false)
K.Options.Write("Nameplates", "target.smoothOpacity", false)
for _, side in ipairs(plate.brackets.sides) do
	assert(not side.keyline:IsShown() and side.open._state.Offset[1] == 0, "E4: off restores stationary, unlined ticks")
	local color = N.Last(side.stroke, "SetVertexColor")
	assert(color[1] == ns.Medallions.GUNMETAL[1], "E4: off restores gunmetal ticks")
end
N.Target(env, "nameplate2")
assert(other:GetAlpha() == 1 and plate:GetAlpha() == 0.4, "E4: off restores immediate plate opacity")
assert(#env._errors == 0 and K.ErrorCount() == 0, tostring(env._errors[1]))
print("nameplate outcome cues ok")
