-- test-auras-medallions-rim.lua: aura tiles use the dark metal rim only in Medallions and can return to the previous black rim.
local A = dofile("Tools/regression/auras_env.lua")
local env, K = A.New({ layout = true })
K.Modules.Enable("Auras")
local parent = env.CreateFrame("Frame", nil, K.Scale.Root())
parent:SetSize(500, 200)
local preview = K.Options.Preview("Auras")(parent)
preview:Refresh()
local rim = preview.buffs[1].rim[1]
local r, g, b = K.Tokens.Color("medSocketRim")
assert(A.W.SameColor(rim, r, g, b, 1), "Medallions aura tiles take the dark metal rim")
K.Options.Write("Auras", "medallionsIcons", false)
preview:Refresh()
assert(A.W.SameColor(rim, K.Tokens.Color("black")), "off restores the original black rim")
K.Options.Write("Auras", "medallionsIcons", true)
K.Options.Write("HudStyle", "style", "frames")
preview:Refresh()
assert(A.W.SameColor(rim, K.Tokens.Color("black")), "Frames keeps its black rim")
assert(#env._errors == 0, tostring(env._errors[1]))
print("ok Medallions aura rim and previous look")
