local W = dofile("Tools/regression/widget_env.lua")
local env, K = W.New({ boot = false })
K.Modules.Register(W.CoreEnv.Module("Chat", { defaults = { size = 12 } }))
K.Modules.Register(W.CoreEnv.Module("ActionBars", { defaults = { count = 12 } }))
W.CoreEnv.Boot(env)
K.Options.Write("Chat", "size", 16)
K.Store.Layout().sample = { x = 80 }
local shared = assert(K.Profiles.Export("Chat"))
K.Options.Write("Chat", "size", 13)
K.Options.Write("ActionBars", "count", 6)
K.Store.Layout().sample.x = 90
local before = K.Store.Export()
local preview = assert(K.Profiles.Preview(shared))
assert(K.Store.Export() == before, "reviewing an import must not apply it")
assert(preview.summary == "Chat", "a scoped import names only the module it changes: " .. preview.summary)
assert(K.Store.Import(preview.text))
assert(K.Options.Read("Chat", "size") == 16 and K.Options.Read("ActionBars", "count") == 6, "a module import preserves other modules")
assert(K.Store.Layout().sample.x == 90, "a module import preserves the layout")
assert(K.Store.Account().restoreProfile:find("Before import", 1, true), "import makes a named backup")
assert(K.Profiles.Restore() and K.Options.Read("Chat", "size") == 13, "one click restores the previous settings")
assert(K.Store.ResetProfile())
assert(K.Store.Account().restoreProfile:find("Before reset", 1, true), "reset makes a named backup")
assert(K.Profiles.Restore() and K.Options.Read("ActionBars", "count") == 6, "reset can be undone")
local layout = assert(K.Profiles.Export("layout"))
K.Store.Layout().sample.x = 100
local review = assert(K.Profiles.Preview(layout))
assert(review.summary == "Layout")
assert(K.Store.Import(review.text) and K.Store.Layout().sample.x == 90)
assert(K.Options.Read("ActionBars", "count") == 6)
local clean = assert(K.Profiles.Export("Chat"))
assert(K.Profiles.Preview(clean).summary == "No changes", "review does not report default values as changes")
assert(K.Profiles.Preview("KSS1:broken") == nil, "bad scoped strings are rejected")
local backups = #K.Store.ListProfiles()
assert(not K.Store.Import("not a profile") and #K.Store.ListProfiles() == backups, "invalid imports create no backup or profile")
assert(#env._errors == 0, tostring(env._errors[1]))
print("profile scopes ok")
