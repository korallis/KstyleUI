-- test-rails-threat-docking.lua: the default threat card follows the guide's foot with a sixteen-unit gap and custom positions win.
local Boot = dofile("Tools/regression/questcard_guide_env.lua")
local M = dofile("Tools/regression/meters_env.lua")
local Load = dofile("Tools/regression/load_files.lua")
local R = Boot({ width = 1920, height = 1080 })
M.Game(R.env, {})
Load(M.Files(), R.env)
R.K.Options.Write("Meters", "followRole", false)
R.K.Options.Write("Meters", "damage.shown", false)
M.Enable(R.env, R.K)
R.K.Options.Write("Meters", "threat.shown", true)
R.settle()
local threat = R.env._addons.KstyleUI_Meters.Threat
local point, relative, on, x, y = threat.holder:GetPoint(1)
local side = R.K.Safe.Side(R.K.Scale.Root())
assert(point == "TOPRIGHT" and relative == side.storyGuide and on == "BOTTOMRIGHT" and math.abs(x) < 1e-6 and y < -R.K.Widgets.Snap(threat.holder, 16),
	"anchor the default threat card sixteen units below the guide and its docked controls")
R.rxp.activeItemFrame:Hide()
R.rxp.targeting.activeTargetFrame:Hide()
R.ns.RestedXP.Rail.Place()
assert(select(2, threat.holder:GetPoint(1)) == R.K.Skin.Parts(R.rxp.RXPFrame).backdrop, "without docked controls the threat card follows the guide's own foot")
R.K.Options.Write("Meters", "threat.followGuide", false)
assert(select(2, threat.holder:GetPoint(1)) == R.K.Scale.Root(), "turning guide following off restores the independent threat position")
R.K.Options.Write("Meters", "threat.followGuide", true)
assert(select(2, threat.holder:GetPoint(1)) == side.storyGuide, "guide following can be enabled again")
R.K.Layout.Update("meters.threat", { x = -900 })
R.ns.RestedXP.Rail.Place()
assert(select(2, threat.holder:GetPoint(1)) == R.K.Scale.Root(), "a custom threat position stays independent of the guide")
assert(#R.env._errors == 0 and R.K.ErrorCount() == 0, tostring(R.env._errors[1]))
print("threat guide docking ok")
