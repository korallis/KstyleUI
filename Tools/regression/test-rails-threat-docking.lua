-- test-rails-threat-docking.lua: the lone threat card keeps its own Layout place while the guide card stands in the top left corner; it no longer follows the guide's foot.
local Boot = dofile("Tools/regression/questcard_guide_env.lua")
local M = dofile("Tools/regression/meters_env.lua")
local Load = dofile("Tools/regression/load_files.lua")
local R = Boot({ width = 1920, height = 1080 })
M.Game(R.env, {})
Load(M.Files(), R.env)
R.K.Options.Write("Meters", "followRole", false)
R.K.Options.Write("Meters", "damage.shown", false)
M.Enable(R.env, R.K)
R.K.Options.Write("Meters", "threat.shown", true)
R.settle()
local threat = R.env._addons.KstyleUI_Meters.Threat
assert(R.K.Skin.Parts(R.rxp.RXPFrame).backdrop:IsVisible(), "the guide card is up")
assert(select(2, threat.holder:GetPoint(1)) == R.K.Scale.Root(), "the default threat card keeps its own place instead of hanging from the guide's foot")
R.ns.RestedXP.Rail.Place()
assert(select(2, threat.holder:GetPoint(1)) == R.K.Scale.Root(), "placing the guide again leaves the threat card where it is")
assert(R.K.Options.Row("Meters", "threat.followGuide") == nil, "the follow-the-guide switch is gone")
assert(#R.env._errors == 0 and R.K.ErrorCount() == 0, tostring(R.env._errors[1]))
print("threat keeps its own place ok")
