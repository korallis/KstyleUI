local S = dofile("Tools/regression/stubs/wow.lua")
local env = S.NewEnv()
for _, quiet in ipairs({ false, true }) do
	env.SetQuiet(quiet)
	local t = env.CreateFrame("Frame"):CreateTexture()
	t:SetAlpha(0)
	t:SetVertexColor(0.5, 0.4, 0.8, 1)
	assert(t:GetAlpha() == 1, "SetVertexColor changes the same alpha aspect as SetAlpha")
	t:SetAlpha(0.25)
	assert(select(4, t:GetVertexColor()) == 0.25, "GetVertexColor sees region alpha")
	t:SetVertexColor(0.5, 0.4, 0.8)
	assert(t:GetAlpha() == 1, "omitted vertex alpha defaults to one")
	t:SetAlpha(0)
	assert(select(4, t:GetVertexColor()) == 0, "a later SetAlpha hides a retinted texture")
	t:SetColorTexture(0.2, 0.3, 0.4, 0.16)
	assert(t:GetAlpha() == 0.16 and select(4, t:GetVertexColor()) == 0.16, "SetColorTexture writes the same alpha")
	t:SetAlpha(0)
	assert(t:GetAlpha() == 0, "SetAlpha after SetColorTexture wins")
	t:SetColorTexture(1, 1, 1)
	assert(t:GetAlpha() == 1, "omitted colour texture alpha defaults to one")
	t:SetAlphaFromBoolean(false)
	assert(t:GetAlpha() == 0, "omitted boolean alpha defaults to zero for false")
	t:SetAlphaFromBoolean(true)
	assert(select(4, t:GetVertexColor()) == 1, "omitted boolean alpha defaults to one for true")
	local label = env.CreateFrame("Frame"):CreateFontString()
	label:SetAlpha(0)
	label:SetTextColor(0.2, 0.3, 0.4, 0.6)
	assert(label:GetAlpha() == 0.6 and select(4, label:GetTextColor()) == 0.6, "FontString colour writes its Alpha aspect")
	label:SetAlpha(0.25)
	assert(select(4, label:GetTextColor()) == 0.25, "FontString alpha is shared with GetTextColor")
	label:SetTextColor(1, 1, 1)
	assert(label:GetAlpha() == 1, "omitted text alpha defaults to one")
end
print("vertex alpha contract passed")
