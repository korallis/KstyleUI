local S = dofile("Tools/regression/stubs/wow.lua")
local env = S.NewEnv()
for _, quiet in ipairs({ false, true }) do
	env.SetQuiet(quiet)
	local t = env.CreateFrame("Frame"):CreateTexture()
	t:SetAlpha(0)
	t:SetVertexColor(0.5, 0.4, 0.8, 1)
	assert(t:GetAlpha() == 0, "SetVertexColor must preserve region alpha; keep the two alpha aspects independent")
	t:SetAlpha(0.25)
	assert(select(4, t:GetVertexColor()) == 1, "GetVertexColor must return vertex alpha independently of SetAlpha")
	t:SetVertexColor(0.5, 0.4, 0.8)
	assert(t:GetAlpha() == 0.25 and select(4, t:GetVertexColor()) == 1, "omitted vertex alpha defaults to one without changing region alpha")
	t:SetVertexColor(0.5, 0.4, 0.8, 0.4)
	t:SetAlpha(0.6)
	assert(select(4, t:GetVertexColor()) == 0.4, "SetAlpha must preserve vertex alpha regardless of setter order")
end
print("vertex alpha contract passed")
