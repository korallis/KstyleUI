-- test-actionbars-quiet-slab.lua: quiet sockets, readable cooldowns and the crest can each return to the previous look.
local AB = dofile("Tools/regression/actionbars_env.lua")
local W = AB.W
local env, K, ns = AB.New({ width = 1920, height = 1080, class = "WARLOCK" })
AB.Enable(env, K)
K.Options.Write("HudStyle", "style", "medallions")
env.RunTimers()
local empty = ns.bars.bar1.buttons[12]
assert(not empty.hasAction and empty:GetAlpha() == 0.4, "dim an empty Medallions socket to 0.4")
K.Options.Write("ActionBars", "quietSockets", false)
assert(empty:GetAlpha() == 1, "quiet sockets off restores the full-strength empty socket")
K.Options.Write("ActionBars", "quietSockets", true)
env.FireEvent("ACTIONBAR_SHOWGRID")
assert(empty:GetAlpha() == 1, "dragging restores empty sockets")
env.FireEvent("ACTIONBAR_HIDEGRID")
assert(empty:GetAlpha() == 0.4, "ending drag dims empty sockets")
assert(ns.Keybind.Enter(), "enter bind mode")
assert(empty:GetAlpha() == 1, "bind mode restores empty sockets")
ns.Keybind.Exit()
assert(empty:GetAlpha() == 0.4, "leaving bind mode restores quiet sockets")
local b = ns.bars.bar1.buttons[1]
b.countdown.GetText = function() error("never read or parse the engine countdown string") end
b:SetCooldown(10, 1.5, true)
assert(W.LastCall(b.cooldown, "SetDrawEdge")[1] == false, "the GCD draws no lit edge")
b:SetCooldown(10, 20, false)
assert(W.LastCall(b.cooldown, "SetDrawEdge")[1] == true, "a real cooldown draws its edge")
b:SetChargeCooldownFromDuration({})
assert(W.LastCall(b.chargeCooldown, "SetEdgeColor")[4] == 0.6, "charge recharges use the quieter edge colour")
assert(math.abs(b.hotkey:GetAlpha() - 0.6) < 1e-6, "a real cooldown dims the keybind once")
b:ClearCooldown()
assert(b.hotkey:GetAlpha() == 1, "clearing the cooldown restores the keybind")
local _, keySize = b.hotkey:GetFont()
assert(keySize >= K.Scale.TEXT_FLOOR, "Medallions keybind respects the 11-unit floor")
for _, style in ipairs({ "frames", "orbs", "medallions" }) do
	K.Options.Write("HudStyle", "style", style)
	env.RunTimers()
	local point = b.hotkey._points[1]
	assert(point[1] == "TOPLEFT" and point[4] > 0 and point[5] < 0, style .. ": keep the readable keybind inside the icon border")
end
local _, numberSize, flags = b.countdown:GetFont()
assert(math.abs(numberSize - b.opts.size * 0.42) < 1 and flags == "OUTLINE", "outline a countdown at 42 percent of the slot")
local savedSize = ns.Config("bar1").size
K.Options.Write("ActionBars", "bar1.size", savedSize * 26.6 / b.opts.size)
assert(K.Widgets.IsFitted(b.countdown) and K.Widgets.IsFitted(b.count), "fit compact countdown and stack text to their socket")
assert(not K.Widgets.IsFitted(b.hotkey), "compact keybinds keep the text floor")
K.Options.Write("ActionBars", "readableCountdown", false)
assert(not K.Widgets.IsFitted(b.countdown) and not K.Widgets.IsFitted(b.count), "turning readability off restores the previous text floor")
K.Options.Write("ActionBars", "bar1.size", savedSize)
K.Options.Write("ActionBars", "readableCountdown", true)
assert(math.abs(ns.Slab.hub.crest:GetWidth() - 123) < 1, "seat the crest at 123 units")
K.Options.Write("ActionBars", "seatedCrest", false)
assert(math.abs(ns.Slab.hub.crest:GetWidth() - 150) < 1, "crest seating off restores the 150-unit canvas")
K.Options.Write("ActionBars", "readableCountdown", false)
assert(b.hotkey._points[1][5] < 0, "readable countdown off restores the old inset key position")
local _, oldKey = b.hotkey:GetFont()
assert(math.abs(oldKey - K.Widgets.FontSize(b.hotkey, 10 * K.Theme.FontScale())) < 0.01, "readable countdown off restores the old keybind size")
K.Options.Write("ActionBars", "quietCooldown", false)
b:SetCooldown(10, 1.5, true)
assert(W.LastCall(b.cooldown, "SetDrawEdge")[1] == true, "quiet cooldown off restores the GCD edge")
assert(W.LastCall(b.chargeCooldown, "SetEdgeColor")[4] == 1, "quiet cooldown off restores the native charge edge")
K.Options.Write("HudStyle", "style", "frames")
assert(empty:GetAlpha() == 1, "Frames empty sockets retain their full opacity")
assert(#env._blocked == 0 and #env._errors == 0, AB.Errors(env))
print("ok quiet slab: independent choices restore sockets, countdowns, GCD edge and crest")
