-- test-perf-visibility.lua: known-hidden effect frames stop their loops without inspecting secret health or alpha.
local W = dofile("Tools/regression/widget_env.lua")
local FX = dofile("Tools/regression/effects_env.lua")
local env, K = W.New({ setup = function(e)
	FX.Install(e)
	e.WorldFrame = e.CreateFrame("Frame", "WorldFrame")
end })
local slot = K.Widgets.Slot(K.Scale.Root())
slot:SetProc(true)
assert(slot.lumenGlow.breath:IsPlaying(), "a visible proc keeps its breath")
slot:Hide()
slot:Paint()
assert(not slot.lumenGlow.breath:IsPlaying(), "P11: stop the proc breath when the slot is hidden")
slot:Show()
assert(slot.lumenGlow.breath:IsPlaying(), "P11: resume a still-active visible proc")
slot.lumenGlow:Hide()
slot:Paint()
assert(not slot.lumenGlow.breath:IsPlaying(), "P11: paint must not play a hidden glow")
K.Options.Write("HudStyle", "style", "medallions")
env.FireEvent("PLAYER_ENTERING_WORLD")
local V = K.Effects.Vignette
assert(V.frame.breath:IsPlaying(), "secret health remains engine-driven")
env.UIParent:Hide()
V.Update()
assert(V.frame:IsVisible() and V.frame.breath:IsPlaying(), "keep a WorldFrame vignette breathing when Alt+Z hides only UIParent")
env.UIParent:Show()
assert(V.frame.breath:IsPlaying(), "P11: showing the interface resumes the breath")
V.frame.IsVisible = function() return env.Secret(true) end
V.Update()
assert(V.frame.breath:IsPlaying(), "P11: unknown visibility must preserve the existing loop without comparing a secret")
V.frame.IsVisible = nil
env.WorldFrame:Hide()
V.Update()
assert(not V.frame.breath:IsPlaying(), "P11: pause only when the vignette is truly not drawn")
env.WorldFrame:Show()
assert(V.frame.breath:IsPlaying(), "P11: resume when its actual parent is shown again")
assert(#env._errors == 0 and K.ErrorCount() == 0, "visibility handling must not inspect secrets")
local fallback, kit = W.New({ setup = FX.Install })
kit.Options.Write("HudStyle", "style", "medallions")
fallback.FireEvent("PLAYER_ENTERING_WORLD")
local vignette = kit.Effects.Vignette
fallback.UIParent:Hide()
vignette.Update()
assert(not vignette.frame.breath:IsPlaying(), "P11: a UIParent fallback really is hidden by Alt+Z")
fallback.UIParent:Show()
assert(vignette.frame.breath:IsPlaying(), "P11: resume a UIParent fallback on show")
print("perf visibility ok")
