local C = dofile("Tools/regression/chat_env.lua")
local env, K, ns = C.New()
C.Enable(env, K)
env.RunTimers()
local selected, other = env.ChatFrame1Tab, env.ChatFrame2Tab
env.FCFTab_UpdateColors(selected, true)
env.FCFTab_UpdateColors(other, false)
selected:SetAlpha(0.1)
other:SetAlpha(0.1)
assert(selected:GetAlpha() == 1 and other:GetAlpha() >= 0.8, "pin selected chat tabs at 1 and other tabs at least 0.8 after client fades")
local line = K.Skin.Parts(selected).underline
assert(select(2, line:GetPoint(1)) == selected.Text and select(4, line:GetPoint(1)) < 0, "underline the tab text with a two-unit overhang")
local _, _, _, _, rise = env.GENERAL_CHAT_DOCK:GetPoint(1)
assert(rise > 0, "keep tab labels in their original header row when the message window moves down")
local g = ns.Panel.Geometry(env.ChatFrame1)
assert(math.abs(g.top - g.divider - K.Scale.Snap(12)) < 1e-6, "leave twelve units between the tab rule and the first message")
local r, gg, b = other.Text:GetTextColor()
local er, eg, eb = K.Tokens.Color("labelMuted")
assert(r == er and gg == eg and b == eb, "inactive tab ink is labelMuted")
assert(K.Tokens.FaceShadow(K.Tokens.FontPath("FolioNames")).alpha == 0.85, "name faces use the 85% shadow")
local U = dofile("Tools/regression/unitframes_env.lua")
local ue, UK, un = U.New()
local name = un.Frames.Get("player").views[1].name
assert(name.inkScrim and name.inkScrim[5]:IsShown(), "Frames bare headers get a feathered scrim")
for _, texture in ipairs(name.inkScrim) do
	local sr, sg, sb, alpha = texture:GetVertexColor()
	assert(texture.inkTextScrim and sr == 0 and sg == 0 and sb == 0 and alpha == 0.45, "only text scrims are marked as soft 45% black backing")
end
local _, owner, _, x, y = name.inkScrim[1]:GetPoint(1)
assert(owner == name and x == -UK.Widgets.Snap(name, 6) and y == UK.Widgets.Snap(name, 4), "scrims extend six units sideways and four above")
local _, bottom, _, bx, by = name.inkScrim[9]:GetPoint(1)
local rx, ry = UK.Widgets.Remainder(name)
local pixel = UK.Scale.Pixel(1) / UK.Widgets.ScaleFactor(name)
assert(bottom == name and math.abs(bx - UK.Widgets.Snap(name, 6) - rx * pixel) < 1e-6
	and math.abs(by + UK.Widgets.Snap(name, 4) + ry * pixel) < 1e-6, "bottom and right padding preserve the exact snapped text box")
UK.Options.Write("HudStyle", "style", "medallions")
assert(not name.inkScrim[5]:IsShown(), "the scrim leaves the backed Medallions slab alone")
local A = dofile("Tools/regression/auras_env.lua")
local _, _, an = A.New()
assert(an.Model.Timer({}).outline == "OUTLINE", "aura timers default to a thin outline")
assert(#ue._errors == 0 and #env._errors == 0, tostring(ue._errors[1] or env._errors[1]))
print("world ink audit passed")
