-- test-perf-slice-build.lua: a slice hidden before the first draw stays unbuilt, and first show reuses every required slice thereafter.
local W = dofile("Tools/regression/widget_env.lua")
local env, K = W.New()
local owner = env.CreateFrame("Frame", nil, K.Scale.Root())
owner:SetSize(100, 40)
local chrome = K.Widgets.Chrome(owner, { shape = "tile" })
owner:Hide()
env.RunTimers()
assert(#owner._regions == 0, "P3: defer each chrome nine-slice until drawn; hiding a newly built owner must not leave 36 unused regions")
owner:Show()
env.RunTimers()
assert(#owner._regions == 27 and #chrome.shadow == 0, "P3: first show builds fill, rim and line in their existing sublevels, keeping the disabled shadow unbuilt")
local before = #owner._regions
chrome:SetProc(true)
chrome:SetProc(false)
chrome:SetEdge("accent")
chrome:SetShown(false)
chrome:SetShown(true)
assert(#owner._regions == before, "P3: hover, proc and later shows must reuse the pre-drawn slice regions")
chrome:SetShadow(true)
K.Options.Write("Widgets", "shadows", true)
assert(#owner._regions == before + 9, "P3: the first enabled shadow creates exactly its own nine pieces")
local engine = env.CreateFrame("AuraButton", nil, K.Scale.Root())
local skin = env.CreateFrame("Frame", nil, engine)
skin:SetSize(20, 20)
local bound = K.Widgets.IconChrome(skin)
assert(#bound.fill == 9 and bound.drawReady, "P3: prepare restricted engine-button art in its initializer before secrecy can begin")
engine._denied = true
env.RunTimers()
local preview = K.Widgets.MarkPreview(env.CreateFrame("Frame", nil, K.Scale.Root()))
local sample = env.CreateFrame("Frame", nil, preview)
sample:SetSize(20, 20)
local fitted = K.Widgets.IconChrome(sample)
assert(#fitted.fill == 9 and fitted.drawReady, "P3: prepare preview slices before Options measures their complete bounds")
assert(#env._errors == 0, table.concat(env._errors, "\n"))
print("perf slice build ok")
