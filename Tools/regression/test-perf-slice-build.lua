-- test-perf-slice-build.lua: first show builds required slices synchronously; hidden owners defer art and later shows reuse it.
local W = dofile("Tools/regression/widget_env.lua")
local env, K = W.New()
local owner = env.CreateFrame("Frame", nil, K.Scale.Root())
owner:SetSize(100, 40)
owner:Hide()
local chrome = K.Widgets.Chrome(owner, { shape = "tile" })
assert(#owner._regions == 0, "P3: defer each chrome nine-slice until drawn; hidden owners must not build unused regions")
owner:Show()
assert(#owner._regions == 27 and #chrome.shadow == 0, "P3: first show builds fill, rim and line in their existing sublevels, keeping the disabled shadow unbuilt")
K.Options.Write("Widgets", "cardMaterial", "Glass")
for _, shape in ipairs({ "tile", "card", "panel" }) do
	local live = env.CreateFrame("Frame", nil, K.Scale.Root())
	live:SetSize(200, 100)
	local art = K.Widgets.Chrome(live, { shape = shape })
	assert(art.fill and rawget(art.fill, 1) and art.rim and rawget(art.rim, 1), "P3: created-visible " .. shape .. " chrome must be complete without flushing timers")
end
local T = dofile("Tools/regression/tooltips_env.lua")
local parent = env.CreateFrame("Frame", nil, K.Scale.Root())
parent:SetSize(200, 100)
parent:Hide()
local child = env.CreateFrame("Frame", nil, parent)
child:SetAllPoints(parent)
local art = K.Widgets.Chrome(child, { shape = "tile" })
T.BlizzardShow(parent, true)
assert(art.fill and rawget(art.fill, 1) and rawget(art.rim, 1), "P3: children shown by Blizzard must draw complete chrome in the same frame")
parent:Hide()
local combatChild = env.CreateFrame("Frame", nil, parent)
combatChild:SetAllPoints(parent)
local combatArt = K.Widgets.Chrome(combatChild, { shape = "tile" })
parent.IsProtected = function() return true end
env.SetCombat(true)
parent:Show()
assert(combatArt.fill and rawget(combatArt.fill, 1), "P3: an unprotected child shown by a protected parent must draw complete chrome in the same combat frame")
env.SetCombat(false)
local scaled = env.CreateFrame("Frame", nil, K.Scale.Root())
scaled:SetScale(0.93)
local previewTile = env.CreateFrame("Frame", nil, scaled)
previewTile:SetSize(24, 24)
local previewArt = K.Widgets.Chrome(previewTile, { shape = "tile" })
local expected = K.Widgets.Snap(previewTile, previewArt:Chamfer())
scaled:SetScale(1)
env.RunTimers()
assert(rawget(previewArt.line, 1):GetWidth() == expected, "P3: preserve the slice's original layout when a preview parent is scaled after construction")
local before = #owner._regions
chrome:SetProc(true)
chrome:SetProc(false)
chrome:SetEdge("accent")
chrome:SetShown(false)
chrome:SetShown(true)
assert(#owner._regions == before, "P3: hover, proc and later shows must reuse the pre-drawn slice regions")
chrome:SetShadow(true)
K.Options.Write("Widgets", "shadows", true)
assert(#owner._regions == before + 9, "P3: the first enabled shadow creates exactly its own nine pieces")
local engine = env.CreateFrame("AuraButton", nil, K.Scale.Root())
local skin = env.CreateFrame("Frame", nil, engine)
skin:SetSize(20, 20)
local bound = K.Widgets.IconChrome(skin)
assert(#bound.fill == 9 and bound.drawReady, "P3: prepare restricted engine-button art in its initializer before secrecy can begin")
engine._denied = true
env.RunTimers()
local preview = K.Widgets.MarkPreview(env.CreateFrame("Frame", nil, K.Scale.Root()))
local sample = env.CreateFrame("Frame", nil, preview)
sample:SetSize(20, 20)
local fitted = K.Widgets.IconChrome(sample)
assert(#fitted.fill == 9 and fitted.drawReady, "P3: prepare preview slices before Options measures their complete bounds")
assert(#env._errors == 0, table.concat(env._errors, "\n"))
print("perf slice build ok")
