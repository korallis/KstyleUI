-- test-render-guard-fill-ink.lua: a clipped ink copy is complete only when an identical visible text covers every glyph.
local Guard = dofile("Tools/render/guard.lua")
local Stubs = dofile("Tools/regression/stubs/wow.lua")
local Scene = dofile("Tools/render/scene.lua")
local env = Stubs.NewEnv({ width = 1920, height = 1080 })
local root = env.CreateFrame("Frame", "GuardDuplexInk", env.UIParent)
root:SetPoint("TOPLEFT", env.UIParent, "TOPLEFT", 100, -100)
root:SetSize(200, 20)
local whole = root:CreateFontString(nil, "OVERLAY")
whole:SetFont("Fonts\\FRIZQT__.TTF", 12, "OUTLINE")
whole:SetAllPoints(root)
whole:SetText("64%")
whole:SetJustifyH("RIGHT")
whole:SetWordWrap(false)
local clip = env.CreateFrame("Frame", nil, root)
clip:SetPoint("TOPLEFT", root, "TOPLEFT")
clip:SetSize(80, 20)
clip:SetClipsChildren(true)
local ink = clip:CreateFontString(nil, "OVERLAY")
ink:SetFont("Fonts\\FRIZQT__.TTF", 12, "")
ink:SetAllPoints(whole)
ink:SetText("64%")
ink:SetJustifyH("RIGHT")
ink:SetWordWrap(false)
local function clipped()
	local n = 0
	for _, finding in ipairs(Guard.Check(Scene.Build(env))) do
		if finding.kind == "clipped" then n = n + 1 end
	end
	return n
end
assert(clipped() == 0, "a fully visible identical label covers the clipped ink layer")
whole:Hide()
assert(clipped() > 0, "a hidden whole label cannot excuse a fragment")
whole:Show()
whole:SetAlpha(0)
assert(clipped() > 0, "a transparent whole label cannot excuse a fragment")
whole:SetAlpha(1)
whole:SetText("65%")
assert(clipped() > 0, "different text cannot excuse a fragment")
whole:SetText("64%")
whole:SetFont("Fonts\\ARIALN.TTF", 12, "OUTLINE")
assert(clipped() > 0, "a different font face cannot excuse a fragment")
whole:SetFont("Fonts\\FRIZQT__.TTF", 13, "OUTLINE")
assert(clipped() > 0, "a different font size cannot excuse a fragment")
whole:SetFont("Fonts\\FRIZQT__.TTF", 12, "OUTLINE")
whole:SetJustifyH("LEFT")
assert(clipped() > 0, "a different alignment cannot excuse a fragment")
whole:SetJustifyH("RIGHT")
whole:ClearAllPoints()
whole:SetPoint("TOPLEFT", root, "TOPLEFT", 10, 0)
whole:SetSize(200, 20)
assert(clipped() == 0, "anchored copies move together")
ink:ClearAllPoints()
ink:SetPoint("TOPLEFT", root, "TOPLEFT")
ink:SetSize(200, 20)
assert(clipped() > 0, "a different position cannot excuse a fragment")
whole:ClearAllPoints()
whole:SetAllPoints(root)
ink:ClearAllPoints()
ink:SetAllPoints(whole)
local cover = env.CreateFrame("Frame", nil, root)
cover:SetAllPoints(root)
cover:SetFrameLevel(root:GetFrameLevel() + 100)
local texture = cover:CreateTexture(nil, "OVERLAY")
texture:SetAllPoints(cover)
texture:SetColorTexture(1, 1, 1, 1)
assert(clipped() > 0, "an occluded whole label cannot excuse a fragment")
cover:Hide()
whole:SetParent(clip)
assert(clipped() > 0, "two partial copies cannot excuse each other")
print("render guard fill ink ok")
