local W = dofile("Tools/regression/widget_env.lua")
local env, K = W.New({ setup = function(e)
	e.GetCVar = function(name) return name == "colorblindSimulator" and "2" or "0" end
end })
assert(K.ColorVision.Mode() == "redGreen", "the default follows the game's red-green filter")
local r, g, b = K.ColorVision.Color(1)
local wr, wg, wb = K.Tokens.Color("visionRGCalm")
assert(r == wr and g == wg and b == wb)
K.Options.Write("ColorVision", "mode", "blueYellow")
assert(K.ColorVision.Mode() == "blueYellow")
K.Options.Write("ColorVision", "mode", "standard")
assert(K.ColorVision.Color(1, 0.2, 0.3, 0.4) == 0.2, "Standard preserves existing alert colours")
local assets = K.ColorVision.DispelAssets()
for _, kind in ipairs({ "Magic", "Curse", "Disease", "Poison", "Enrage" }) do assert(assets[kind].asset) end
assert(not assets.None, "an unclassified aura must never be inferred to be Enrage")
assert(K.Tokens.Size("body") == 12)
K.Profiles.Readable("Readable")
for role, size in pairs({ body = 14, names = 14, caption = 12, number = 16, timer = 14, time = 14 }) do
	assert(K.Tokens.Size(role) == size, "Readable needs " .. role .. " at " .. size)
end
K.Profiles.Readable("Standard")
assert(K.Tokens.Size("body") == 12, "Standard keeps the shipped text")
local before = K.Store.Export()
env.C_AddOns = { IsAddOnLoaded = function(name) return name == "Bartender4" end }
assert(K.Setup.Integrations.Note("ActionBars", "none"):find("Bartender4", 1, true))
assert(K.Store.Export() == before, "detection never switches any addon or setting off")
assert(K.Options.Read("Integrations", "timerLane") and K.Options.Read("Integrations", "announcementLane") and K.Options.Read("Integrations", "weakAuras"), "new integration settings default on")
K.Options.Write("Integrations", "weakAuras", true)
assert(env.KstyleUI_WeakAuras1 and env.KstyleUI_WeakAuras2, "the two optional named anchors exist")
assert(K.Layout.Element("integrations.KstyleUI_WeakAuras1"), "the anchors are movable")
assert(#env._errors == 0, tostring(env._errors[1]))

K.Options.Write("Integrations", "notices", false)
assert(K.Setup.Integrations.Note("ActionBars", "usual note") == "usual note", "Other-addon notices off restores the usual module note")
K.Setup.Open(false)
assert(K.Setup.window.moduleNote:GetText() == "Every module starts on. Turn off any you do not want.", "Other-addon notices off restores the previous setup help")
K.Options.Write("Integrations", "notices", true)
K.Setup.Open(false)
assert(K.Setup.window.moduleNote:GetText():find("Off keeps your other addon", 1, true), "reopening setup refreshes the addon-choice help")
K.Setup.window:Close()
K.Options.Write("Integrations", "weakAuras", false)
assert(not env.KstyleUI_WeakAuras1:IsShown() and not K.Layout.Live("integrations.KstyleUI_WeakAuras1"), "WeakAuras anchors off restores the previous empty space")
local sample = env.CreateFrame("Frame", nil, K.Scale.Root())
K.Widgets.Size(sample, 100, 50)
K.Layout.Register(sample, "accessibility.sample", { anchor = "CENTER", x = 0, y = 0 })
K.Layout.Enter()
local toolbar, plate = K.Layout.Mode.Toolbar(), K.Layout.Mode.Plate("accessibility.sample")
assert(plate.tag:IsShown())
K.Options.Write("LayoutControls", "clearMovers", false)
K.Options.Write("LayoutControls", "search", false)
assert(not plate.tag:IsShown() and plate.label:GetPoint() == "CENTER", "See-through movers off restores the centred label without a tag")
assert(not toolbar.search:IsShown() and not toolbar.elements:IsShown(), "Element search off restores the previous toolbar")
K.Options.Write("LayoutControls", "clearMovers", true)
K.Options.Write("LayoutControls", "search", true)
assert(plate.tag:IsShown() and toolbar.search:IsShown())
K.Layout.Exit(true)
assert(#env._errors == 0, tostring(env._errors[1]))

print("accessibility ok")
