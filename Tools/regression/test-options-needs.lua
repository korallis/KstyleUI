local O = dofile("Tools/regression/options_env.lua")
local W = O.W
local env, K, ns = O.New({ before = function(_, K)
	K.Modules.Register(W.CoreEnv.Module("ActionBars", { defaults = { size = 20, bindingHints = true } }))
	K.Options.Register("ActionBars", { { type = "header", label = "Buttons" }, { type = "slider", key = "size", label = "Size", help = "The size of the buttons.", min = 10, max = 40, step = 2 } })
end })
local general = ns.Pages.Find(ns.Pages.List(), "General")
assert(O.Find(ns.Model.PageItems(general), function(item) return item.kind == "header" and item.label == "Text preset" end), "Give the Readable preset its own Text preset section so it does not duplicate Readability")
local entered = 0
env.SlashCmdList.KSTYLEKB = function() entered = entered + 1 end
K.Options.Open("ActionBars")
W.Settle(env)
env.RunTimers()
local page = ns.Pages.Find(ns.Pages.List(), "ActionBars")
local bind = O.Find(ns.Model.PageItems(page), function(item) return item.label == "Bind keys" end)
assert(bind and bind.buttons[1].onClick, "Action Bars must have a visible Bind keys button")
bind.buttons[1].onClick()
assert(entered == 1)
local row
for _, candidate in ipairs(ns.Window.Parts().content.rows) do
	if candidate.item and candidate.item.key == "size" then row = candidate end
end
assert(row, "the size row is visible")
local slider = row.controls.slider
assert(slider.edit:GetWidth() == 56)
W.Click(slider.valueButton)
assert(slider.edit:IsShown() and W.LastCall(slider.edit, "SetFocus"), "clicking a value starts typing")
assert(not slider.readout:IsShown(), "the old readout must not double-print behind the editor")
slider.edit:SetText("29")
slider.edit:GetScript("OnEnterPressed")(slider.edit)
slider.edit:GetScript("OnHide")(slider.edit)
env.RunTimers()
W.Settle(env)
assert(slider.readout:IsShown(), "closing the editor restores the readout")
assert(K.Options.Read("ActionBars", "size") == 30, "typed input obeys the slider's step")
assert(K.Options.IsChanged("ActionBars", "size"))
W.Settle(env)
assert(row.changed:IsShown() and row.changed:GetWidth() == K.Widgets.Snap(row, 4), "changed settings have a four-unit diamond")
row:GetScript("OnMouseUp")(row, "RightButton")
env.RunTimers()
W.Settle(env)
assert(K.Options.Read("ActionBars", "size") == 20, "right-click restores the default")
assert(K.Layout.Enter())
W.Settle(env)
local toolbar = K.Layout.Mode.Toolbar()
assert(toolbar.bind and toolbar.search and toolbar.elements, "Layout Mode exposes Bind keys and a searchable element list")
toolbar.search:SetText("toolbar")
toolbar.search:GetScript("OnTextChanged")(toolbar.search, true)
W.Click(toolbar.bind)
assert(entered == 2 and not K.Layout.IsActive(), "binding exits Layout Mode before entering")
K.Options.Write("Integrations", "timerLane", false)
K.Options.Write("Integrations", "announcementLane", false)
K.Options.Open("General")
env.RunTimers()
W.Settle(env)
local preview = ns.Window.Parts().preview
local standard = preview.current
for i, item in ipairs(ns.Window.State().items) do
	if item.kind == "header" and item.label == K.L["Existing addons"] then ns.Window.Parts().content:ScrollToIndex(i, true, "TOP"); break end
end
K.Options.Write("Integrations", "timerLane", true)
K.Options.Write("Integrations", "announcementLane", true)
env.RunTimers()
W.Settle(env)
assert(preview.current ~= standard, "opting into boss lanes must replace the Existing addons sample immediately")
assert(preview.current:GetWidth() == K.Widgets.Snap(preview.current, 520) and preview.current:GetHeight() == K.Widgets.Snap(preview.current, 190), "the lane sample snaps its 520 by 190 canvas at the fitted preview scale")
K.Options.Write("Integrations", "timerLane", false)
K.Options.Write("Integrations", "announcementLane", false)
env.RunTimers()
W.Settle(env)
assert(preview.current == standard, "turning both lanes off restores the cached General sample")
assert(#env._errors == 0, tostring(env._errors[1]))

K.Options.Write("ActionBars", "bindingHints", false)
page = ns.Pages.Find(ns.Pages.List(), "ActionBars")
assert(not O.Find(ns.Model.PageItems(page), function(item) return item.label == "Bind keys" end), "Binding helpers off hides the new page button")
K.Layout.Enter()
assert(not toolbar.bind:IsShown(), "Binding helpers off also restores the previous toolbar")
K.Layout.Exit(true)
K.Options.Write("OptionControls", "numericInput", false)
K.Options.Write("OptionControls", "changedSettings", false)
K.Options.Open("ActionBars")
K.Options.Write("ActionBars", "size", 30)
env.RunTimers()
W.Settle(env)
for _, candidate in ipairs(ns.Window.Parts().content.rows) do if candidate.item and candidate.item.key == "size" then row = candidate end end
slider = row.controls.slider
assert(not slider.valueButton:IsShown() and not row.changed:IsShown(), "Settings helpers off restores the old value and label")
assert(not slider.edit:IsShown())
row:GetScript("OnMouseUp")(row, "RightButton")
assert(K.Options.Read("ActionBars", "size") == 30, "Quick reset off restores the previous right-click behaviour")
K.Options.Write("ProfileTools", "review", false)
K.Options.Write("ProfileTools", "backups", false)
page = ns.Pages.Find(ns.Pages.List(), "Profiles")
local items = ns.Model.PageItems(page)
assert(not O.Find(items, function(item) return item.label == "Share scope" or item.label == "Restore backup" end), "Profile helpers off restores the previous share controls")
assert(#env._errors == 0, tostring(env._errors[1]))

K.Options.Write("ProfileTools", "review", true)
local shared = assert(K.Profiles.Export("ActionBars"))
K.Options.Write("ActionBars", "size", 22)
assert(ns.Pages.ReviewImport(shared))
local previewImport = K.Profiles.Preview
K.Profiles.Preview = function() error("Apply must use the approved preview without decoding it again") end
local host = K.Widgets.DialogHost()
W.Click(host.visibleButtons[#host.visibleButtons])
K.Profiles.Preview = previewImport
assert(K.Options.Read("ActionBars", "size") == 30, "Apply imports the approved scoped payload")
assert(#env._errors == 0, tostring(env._errors[1]))
print("options needs ok")
