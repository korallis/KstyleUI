-- test-spec-layouts.lua: spec positions overlay the profile, defer in combat, survive sharing and leave its look intact.
local W = dofile("Tools/regression/widget_env.lua")

for _, screen in ipairs({ { 1920, 1080 }, { 2560, 1440 }, { 5120, 1440 }, { 3840, 2160 } }) do
	local env, K = W.New({ width = screen[1], height = screen[2], setup = function(e)
		e._spec = 1
		e.GetNumSpecializations = function() return 2 end
		e.C_SpecializationInfo = {
			GetSpecialization = function() return e._spec end,
			GetSpecializationInfo = function(i) return i, i == 1 and "Arms" or "Protection", nil, nil, "DAMAGER" end,
		}
	end })
	local S, P, Layout = K.Specialization, K.Profiles, K.Layout
	local frame = env.CreateFrame("Frame", nil, K.Scale.Root(), "SecureHandlerBaseTemplate")
	frame:SetSize(120, 30)
	Layout.Register(frame, "spec.sample", { anchor = "CENTER", x = 10, y = 20 }, { scalable = true, resizable = true })
	assert(Layout.Set("spec.sample", "x", 40))
	assert(Layout.Set("spec.sample", "width", 150))
	assert(Layout.Set("spec.sample", "scale", 1.2))
	assert(Layout.Set("spec.sample", "alphaIdle", 0.7))
	K.Store.Module("Appearance").motion = "off"
	assert(P.SaveLayout("Tank"))
	assert(not P.SaveLayout("Tank") and not P.SaveLayout("bad|name"))
	assert(Layout.Set("spec.sample", "x", 90))
	local base = K.Options.Copy(K.Store.Layout())
	assert(S.AssignLayout("spec:2", "Tank"))
	assert(S.Layout("spec:1") == "" and S.Layout("spec:2") == "Tank")
	assert(Layout.Get("spec.sample").x == 90, "assigning another spec leaves the current positions")
	local function switch(spec)
		env._spec = spec
		env.FireEvent("PLAYER_SPECIALIZATION_CHANGED", "player")
	end
	switch(2)
	assert(Layout.Get("spec.sample").x == 40 and K.Store.ProfileName() == "Default")
	local look = Layout.Get("spec.sample")
	assert(look.width == 150 and look.scale == 1.2 and look.alphaIdle == 0.7)
	assert(K.Store.Module("Appearance").motion == "off")
	assert(K.Options.Equal(base, K.Store.Layout()), "applying named positions never overwrites the profile's places")
	assert(Layout.Enter())
	Layout.Set("spec.sample", "x", 55)
	Layout.Exit(false)
	assert(Layout.Get("spec.sample").x == 40, "cancel restores named positions")
	Layout.Set("spec.sample", "x", 45)
	assert(P.Layouts().Tank["spec.sample"].x == 45, "editing an applied layout updates its own positions")
	assert(K.Options.Equal(base, K.Store.Layout()))
	switch(1)
	assert(Layout.Get("spec.sample").x == 90, "switching back restores the profile")
	local original = frame.SetPoint
	frame.SetPoint = function(self, ...)
		assert(not env._combat, "protected moves must wait for Combat.Queue")
		return original(self, ...)
	end
	env.SetCombat(true)
	switch(2)
	env.FireEvent("ACTIVE_TALENT_GROUP_CHANGED")
	assert(Layout.Get("spec.sample").x == 90 and K.Combat.Pending() == 1)
	env.SetCombat(false)
	assert(Layout.Get("spec.sample").x == 45)
	env.SetCombat(true)
	switch(1)
	switch(2)
	env.SetCombat(false)
	assert(Layout.Get("spec.sample").x == 45, "combat settlement uses the latest spec")
	assert(P.SaveLayout("Other"))
	local share = assert(P.Export("layout"))
	env.SetCombat(true)
	assert(P.DeleteLayout("Tank"))
	assert(Layout.Get("spec.sample").x == 45, "deleting an applied layout waits for combat to end")
	env.SetCombat(false)
	assert(S.Layout("spec:2") == "" and Layout.Get("spec.sample").x == 90, "delete in use falls back")
	local review = assert(P.Preview(share))
	assert(K.Store.Import(review.text))
	assert(P.Layouts().Tank["spec.sample"].x == 45, "layout sharing round trips named positions")
	local settings = assert(P.Export("everything", false))
	assert(P.DeleteLayout("Tank"))
	assert(K.Store.Import(assert(P.Preview(settings)).text))
	assert(P.Layouts().Tank == nil, "settings-only sharing omits named layouts")
	assert(K.Store.Layout()["spec.sample"].x == 90, "settings-only sharing preserves the receiving layout")
	local module = assert(P.Export("Appearance"))
	local decoded = assert(K.Store.Decode(assert(P.Preview(module)).text))
	assert(decoded.namedLayouts == nil, "a module import cannot carry named layouts")
	local payload = assert(K.Store.Decode(K.Store.Export()))
	payload.namedLayouts = { Broken = { sample = { width = 400 } } }
	assert(not K.Store.Decode(W.CoreEnv.CraftLua(payload)), "a named layout may contain positions only")
	local full = assert(K.Store.Export())
	local settingsOnly = assert(K.Store.Decode(assert(P.Preview(full, nil, false)).text))
	assert(settingsOnly.namedLayouts == nil and K.Options.Equal(settingsOnly.layout, K.Store.Layout()), "the receiver can exclude layout from a full share")
	P.Layouts().Other["spec.sample"].x = 12
	assert(K.Store.Import(full))
	assert(P.Layouts().Other["spec.sample"].x == 12 and P.Layouts()["Other 2"]["spec.sample"].x == 45, "imports preserve conflicting existing names")
	K.Store.SetProfile("Manual")
	assert(P.DeleteLayout("Other 2"))
	assert(K.Store.ProfileName() == "Manual", "deleting an unused layout preserves a manual profile choice")
	assert(K.Store.CreateProfile("Tank look"))
	assert(S.Assign("spec:1", "Default"))
	assert(S.Assign("spec:2", "Tank look"))
	assert(S.AssignLayout("spec:2", "Other"))
	assert(K.Store.ProfileName() == "Tank look" and Layout.Get("spec.sample").x == 12)
	S.SetEnabled(false)
	assert(Layout.Get("spec.sample").x == 10, "disabling spec switching restores the chosen profile's layout")
	S.SetEnabled(true)
	assert(Layout.Get("spec.sample").x == 12)
	switch(1)
	assert(K.Store.ProfileName() == "Default" and Layout.Get("spec.sample").x == 90)
	switch(2)
	assert(K.Store.ProfileName() == "Tank look" and Layout.Get("spec.sample").x == 12, "profile switches apply their named positions afterwards")
	W.CoreEnv.Logout(env)
	local again, A = W.New({ saved = env.KstyleUIDB })
	assert(A.Profiles.Layouts().Other["spec.sample"].x == 12, "the library survives logout")
	assert(K.ErrorCount() == 0 and #env._errors == 0 and #again._errors == 0)
end
print("spec layouts ok on four screens")
