"""Generate the shipped transport IDs from the curated source beside this file."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
items = json.loads(Path(__file__).with_suffix(".json").read_text(encoding="utf-8"))
target = root / "KstyleUI_ActionBars" / "TravelItems.lua"
text = "-- TravelItems.lua: generated by Tools/data/travel-items.py; edit Tools/data/travel-items.json.\nlocal _, ns = ...\n\nns.TRAVEL_ITEMS = { " + ", ".join(str(i) for i in sorted(map(int, items))) + " }\n"
target.write_bytes(text.replace("\n", "\r\n").encode("ascii"))
